-- 1. Catálogo de módulos del sistema
CREATE TABLE MODULOS (
    ID_MODULO  VARCHAR2(30)  PRIMARY KEY,
    NOMBRE     VARCHAR2(80)  NOT NULL,
    RUTA       VARCHAR2(100) NOT NULL,
    ICONO      VARCHAR2(50),
    ORDEN      NUMBER        DEFAULT 0
);

-- 2. Permisos por tipo de usuario (rol)
CREATE TABLE PERMISOS_TIPO_USUARIO (
    ID_TIPO_USUARIO VARCHAR2(10),
    ID_MODULO       VARCHAR2(30),
    PUEDE_VER       NUMBER(1) DEFAULT 0 NOT NULL,
    PUEDE_CREAR     NUMBER(1) DEFAULT 0 NOT NULL,
    PUEDE_EDITAR    NUMBER(1) DEFAULT 0 NOT NULL,
    PUEDE_ELIMINAR  NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PERM_TU PRIMARY KEY (ID_TIPO_USUARIO, ID_MODULO),
    CONSTRAINT FK_PERM_TU FOREIGN KEY (ID_TIPO_USUARIO) REFERENCES TIPO_USUARIO(ID_TIPO_USUARIO),
    CONSTRAINT FK_PERM_MOD FOREIGN KEY (ID_MODULO) REFERENCES MODULOS(ID_MODULO),
    CONSTRAINT CHK_PERM_VER  CHECK (PUEDE_VER       IN (0,1)),
    CONSTRAINT CHK_PERM_CRE  CHECK (PUEDE_CREAR     IN (0,1)),
    CONSTRAINT CHK_PERM_EDI  CHECK (PUEDE_EDITAR    IN (0,1)),
    CONSTRAINT CHK_PERM_ELI  CHECK (PUEDE_ELIMINAR  IN (0,1))
);

